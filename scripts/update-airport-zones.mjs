import {writeFile, mkdir} from 'node:fs/promises';
const revision='a89e4e0dda9d9878337e2da190ebe1ef1d6af705';
const base=`https://raw.githubusercontent.com/mwgg/Airports/${revision}/`;
const response=await fetch(base+'airports.json');
if(!response.ok)throw new Error('Airport catalogue unavailable');
const airports=await response.json(), groups=new Map();
for(const airport of Object.values(airports)){
  if(!/^[A-Z]{3}$/.test(airport.iata)||typeof airport.tz!=='string')continue;
  try{new Intl.DateTimeFormat('en',{timeZone:airport.tz});}catch{continue;}
  const zones=groups.get(airport.iata)??new Set();zones.add(airport.tz);groups.set(airport.iata,zones);
}
const zones=Object.fromEntries([...groups].filter(([,values])=>values.size===1).sort(([a],[b])=>a.localeCompare(b)).map(([iata,values])=>[iata,[...values][0]]));
const license=await fetch(base+'LICENSE');if(!license.ok)throw new Error('License unavailable');
