await writeFile(new URL('../third_party/mwgg-airports-LICENSE',import.meta.url),(await license.text()).trimEnd()+'\n');
await writeFile(new URL('../src/airport-zones.ts',import.meta.url),`// Generated by scripts/update-airport-zones.mjs from mwgg/Airports ${revision} (MIT).\n// Only unambiguous IATA mappings with runtime-supported IANA zones are included.\nexport const catalogueRevision='${revision}';\nexport const airportZones:Readonly<Record<string,string>>=Object.freeze(${JSON.stringify(zones,null,2)});\n`);
