import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import {createServer} from 'node:http';
import {test as base,expect} from '@playwright/test';
import {Client} from '@modelcontextprotocol/sdk/client/index.js';
import {StreamableHTTPClientTransport} from '@modelcontextprotocol/sdk/client/streamableHttp.js';
import {embedded,migrate} from '../../dist/src/database.js';
import {Core} from '../../dist/src/core.js';
import {createApp} from '../../dist/src/app.js';
import {itineraryRoutes} from '../../dist/src/itinerary-web.js';
import {stayCriteria,stayObservation} from '../../dist/tests/fixtures/stays.js';

const test=base.extend({
  app:async({},use)=>{
    const db=await embedded(),http=createServer(),client=new Client({name:'isolated-stay-browser-client',version:'1'});
    try{
      await migrate(db);const core=new Core(db,false,false),owner=randomUUID(),ownerToken=randomUUID(),clientId='fictional-stay-browser';
      await db.query('insert into client_grants values($1,$2,$3,null)',[owner,clientId,['read','write']]);
      const authenticate=async header=>{if(header===`Bearer ${ownerToken}`)return {userId:owner,clientId};throw Error('Unknown fixture identity');};
      await new Promise(resolve=>http.listen(0,'127.0.0.1',resolve));const origin=`http://127.0.0.1:${http.address().port}`;
      http.on('request',createApp({core,publicOrigin:origin,authenticate,itinerary:itineraryRoutes({core,origin,local:true,authenticate})}));
      await client.connect(new StreamableHTTPClientTransport(new URL(`${origin}/mcp`),{requestInit:{headers:{authorization:`Bearer ${ownerToken}`}}}));
      const tool=async(name,args)=>{const result=await client.callTool({name,arguments:args});assert.ok(!result.isError,JSON.stringify(result));return result.structuredContent;};
      const trip=await tool('create_trip',{idempotencyKey:randomUUID(),name:'Fictional Zermatt group stay — MCP to web',destination:'Fictional Zermatt',startDate:'2027-02-11',endDate:'2027-02-14',adults:10});
      const decision=await tool('create_stay_decision',{idempotencyKey:randomUUID(),tripId:trip.tripId,title:'Hotel rooms versus a whole chalet',criteria:stayCriteria()});
      const hotel=await tool('save_stay_candidate',{idempotencyKey:randomUUID(),decisionId:decision.decisionId,expectedRevision:1,observation:stayObservation()});
      const home=await tool('save_stay_candidate',{idempotencyKey:randomUUID(),decisionId:decision.decisionId,expectedRevision:2,observation:stayObservation(10,'entire_home')});
      await tool('set_stay_disposition',{idempotencyKey:randomUUID(),decisionId:decision.decisionId,expectedRevision:3,candidateId:home.candidateId,disposition:'saved',rationale:'Fictional group prefers a kitchen and shared lounge.'});
      await use({db,origin,ownerToken,tool,tripId:trip.tripId,decisionId:decision.decisionId,hotel,home,webPath:decision.webPath});
    }finally{await client.close();http.closeAllConnections();await new Promise(resolve=>http.close(resolve));await db.close();}
  },
});

test('MCP lodging shortlist opens in the built web app, is reviewed into one tentative item and reads back through MCP',async({browser,app},testInfo)=>{
  const context=await browser.newContext({viewport:{width:390,height:844},serviceWorkers:'block'}),externalRequests=[],pageErrors=[];
  await context.route('**/*',route=>{if(new URL(route.request().url()).origin===app.origin)return route.continue();externalRequests.push(route.request().url());return route.abort('blockedbyclient');});
  const page=await context.newPage();page.on('pageerror',e=>pageErrors.push(e.message));
  try{
    await page.goto(`${app.origin}${app.webPath}&view=details`);
    await page.getByLabel('Local development token').fill(app.ownerToken);
    await page.getByRole('button',{name:'Open local trips',exact:true}).click();
    await expect(page.locator('#trip-title')).toHaveText('Fictional Zermatt group stay — MCP to web');
    await expect(page.locator('body')).toContainText('Hotel rooms versus a whole chalet');
    await expect(page.locator('body')).toContainText('Fictional Matterhorn Hotel');
    await expect(page.locator('body')).toContainText('Fictional Alpine Chalet');
    await expect(page.locator('body')).toContainText('Fictional group prefers a kitchen and shared lounge.');
    const comparison=page.getByRole('table',{name:'Whole-party lodging alternatives — reported evidence'});
    await expect(comparison).toContainText('2027-02-11 → 2027-02-14 · 10 adults');
    await expect(comparison).toContainText('10 beds / 10 places');
    await expect(comparison).toContainText('3,000.00');
    await expect(comparison).toContainText('3,010.00');
    const home=page.getByRole('article',{name:'Fictional Alpine Chalet',exact:true});
    await expect(home).toContainText('1,000.00');
    await home.getByText('Full stay details and source',{exact:true}).click();
    await expect(home.getByRole('link',{name:'Open source ↗'})).toHaveAttribute('href','https://chalet.example/stay');
    await expect(home).toContainText('Fully refundable until the stated deadline');
    await home.getByText('Full stay details and source',{exact:true}).click();
    await page.locator('#stay-research').screenshot({path:testInfo.outputPath('lodging-mobile.png')});
    await page.setViewportSize({width:1280,height:900});
    await page.locator('#stay-research').screenshot({path:testInfo.outputPath('lodging-desktop.png')});
    await page.setViewportSize({width:390,height:844});
    await page.getByRole('button',{name:'Add lodging option',exact:true}).click();
    const capture=page.locator('#stay-option-dialog');
    await capture.getByLabel('Property name',{exact:true}).fill('Fictional Source-only Annex');
    await capture.getByLabel('Configuration name',{exact:true}).fill('Room allocation still unconfirmed');
    await capture.getByLabel('Adults covered by this quote',{exact:true}).fill('10');
    await capture.getByLabel('Unit name',{exact:true}).fill('Proposed allocation');
    await capture.getByLabel('Base price — whole stay, all rooms',{exact:true}).fill('800');
    await capture.getByLabel('Evidence type',{exact:true}).selectOption('sourced');
    await capture.getByLabel('Source label',{exact:true}).fill('Fictional manually reviewed listing');
    await capture.getByLabel('Source URL',{exact:true}).fill('https://annex.example/stay');
    await capture.getByRole('button',{name:'Save observation',exact:true}).click();
    await expect(capture).not.toBeVisible();
    const annex=page.getByRole('article',{name:'Fictional Source-only Annex',exact:true});
    await expect(annex).toContainText('Unknown — no complete equal-basis total');
    await expect(annex).toContainText('Unknown places');
    await home.getByRole('button',{name:'Review this option',exact:true}).click();
    const selection=page.locator('#stay-select-dialog');
    const rationale='Reviewed fictional dates, full-party cost and ten known sleeping places; confirm again before booking.';
    await selection.getByLabel('Selection rationale',{exact:true}).fill(rationale);
    await selection.getByRole('button',{name:'Select this observation',exact:true}).click();
    await expect(selection).not.toBeVisible();
    const selected=page.getByRole('region',{name:'Selected stay evidence'});
    await expect(selected).toContainText(rationale);
    await selected.getByRole('button',{name:'Review tentative stay',exact:true}).click();
    const commit=page.locator('#stay-commit-dialog');
    await expect(commit).toContainText(/no reservation is made/i);
    await commit.getByRole('button',{name:'Save tentative stay to itinerary',exact:true}).click();
    await expect(commit).not.toBeVisible();
    const fresh=await app.tool('get_stay_decision',{decisionId:app.decisionId});
    expect(fresh.candidates).toHaveLength(3);
    expect(fresh.candidates.map(c=>c.id)).toEqual(expect.arrayContaining([app.hotel.candidateId,app.home.candidateId]));
    expect(fresh.selection.observationId).toBe(app.home.observationId);
    expect(fresh.selection.candidateId).toBe(app.home.candidateId);
    expect(fresh.selection.rationale).toBe(rationale);
    expect(fresh.selection.observation).toEqual(stayObservation(10,'entire_home'));
    expect(fresh.links).toHaveLength(1);
    const plan=await app.tool('get_itinerary',{tripId:app.tripId});
    expect(plan.items).toHaveLength(1);
    expect(plan.items[0].payload.status).toBe('tentative');
    expect(plan.items[0].sourceLink).toMatchObject({decisionId:app.decisionId,candidateId:app.home.candidateId,observationId:app.home.observationId,selectionId:fresh.selection.id});
    expect(plan.items[0].id).toBe(fresh.links[0].itemId);
    await expect(page.locator('#timeline')).toContainText('Fictional Alpine Chalet');
    await expect(page.locator('#timeline')).toContainText('Tentative');
    expect((await app.db.query('select count(*)::int n from itinerary_items')).rows[0].n).toBe(1);
    expect((await app.db.query('select count(*)::int n from itinerary_events')).rows[0].n).toBe(1);
    expect((await app.db.query('select count(*)::int n from booking_records')).rows[0].n).toBe(0);
    expect((await app.db.query('select count(*)::int n from search_runs')).rows[0].n).toBe(0);
    await page.getByRole('button',{name:'New lodging comparison',exact:true}).click();
    const creation=page.locator('#stay-decision-dialog');
    await creation.getByLabel('Comparison title',{exact:true}).fill('Fictional web-only fallback');
    await creation.getByRole('button',{name:'Create lodging comparison',exact:true}).click();
    await expect(creation).not.toBeVisible();
    await expect(page.locator('#stay-research')).toContainText('Fictional web-only fallback');
    await page.getByRole('button',{name:'Add lodging option',exact:true}).click();
    await capture.getByLabel('Property name',{exact:true}).fill('Fictional manual guesthouse');
    await capture.getByLabel('Configuration name',{exact:true}).fill('Proposed room block');
    await capture.getByLabel('Unit name',{exact:true}).fill('Unconfirmed room allocation');
    await capture.getByLabel('Source label',{exact:true}).fill('Fictional organizer note');
    await capture.getByRole('button',{name:'Save observation',exact:true}).click();
    await expect(capture).not.toBeVisible();
    const webDecisionId=new URL(page.url()).searchParams.get('stay');
    expect(webDecisionId).not.toBe(app.decisionId);
    const manuallySaved=await app.tool('get_stay_decision',{decisionId:webDecisionId});
    expect(manuallySaved.criteria.adults).toBe(10);
    expect(manuallySaved.candidates).toHaveLength(1);
    expect(manuallySaved.candidates[0].observations[0].payload).toMatchObject({propertyName:'Fictional manual guesthouse',quotedAdults:null,baseTotalMinor:null,source:{kind:'manual',url:null,label:'Fictional organizer note'}});
    expect(manuallySaved.results[0]).toMatchObject({totalMinor:null,sleepingPlaces:null,eligibility:'conditional'});
    expect((await app.db.query('select count(*)::int n from itinerary_items')).rows[0].n).toBe(1);
    expect(externalRequests).toEqual([]);expect(pageErrors).toEqual([]);
  }finally{await context.close();}
});
