import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { test } from "./fixture.mjs";
import { openDisclosure } from "./navigation.mjs";
const key = () => ({ idempotencyKey: randomUUID() });
function deferred() {
  let resolve;
  const promise = new Promise((r) => resolve = r);
  return { promise, resolve };
}
for (const viewport of [{ width: 1280, height: 900 }, { width: 390, height: 844 }]) {
  test(`lifecycle reconciliation after sharing/discussion at ${viewport.width}px`, async ({ page, context, app }) => {
    await page.setViewportSize(viewport);
    const { core, db, owner, origin } = app;
    const { tripId } = await app.call("create_trip", { name: "Fictional lifecycle trip", destination: "Fixture", startDate: "2027-01-01", endDate: "2027-01-02", adults: 2 });
    const errors = [];
    page.on("pageerror", (error) => errors.push(error.message));
    await context.route("**/*", (route) => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
    const state = () => core.callFromWeb("get_itinerary", { tripId }, owner);
    const mutationCount = async () => (await db.query("select count(*)::int n from mutation_requests")).rows[0].n;
    const response = (operation) => page.waitForResponse((r) => r.url() === `${origin}/itinerary-api/${operation}`);
    const action = async (operation, status = 200) => {
      await openDisclosure(page, "plan-more");
      await openDisclosure(page, "trip-actions");
      const replied = response(`${operation}_trip`);
      await page.locator(`#${operation}-trip`).click();
      assert.equal((await replied).status(), status);
      if (status === 200) await page.waitForFunction((text) => document.getElementById("status")?.textContent?.startsWith(text), operation === "archive" ? "Trip archived." : "Trip restored.");
      else await page.waitForFunction(() => document.getElementById("status")?.textContent?.includes("trip changed"));
    };
    const archived = async () => {
      await openDisclosure(page, "trip-switcher");
      await page.locator("#trip-filter").selectOption("archived");
      await page.locator("#trip-archived").waitFor({ state: "visible" });
    };
    const share = async () => {
      await page.locator("#share-trip").click();
      await page.locator("#invite-label").fill("Fixture link");
      const replied = response("create_itinerary_view_link");
      await page.locator("#create-invitation").click();
      return replied;
    };
    const closeShare = () => page.locator('[data-close="share-dialog"]').click();
    const comment = async (body) => {
      await openDisclosure(page, "plan-more");
      await page.locator("#trip-discussion").click();
      await page.locator("#comment-body").fill(body);
      const replied = response("add_itinerary_comment");
      await page.locator('#comment-form button[type="submit"]').click();
      assert.equal((await replied).status(), 200);
      await page.getByText(body, { exact: true }).waitFor();
      await page.locator("#discussion-close").click();
    };
    await page.goto(origin + "/itinerary?trip=" + tripId);
    await page.locator("#local-token").fill(app.ownerToken);
    await page.locator("#local-login button").click();
    await page.locator("#trip-title").getByText("Fictional lifecycle trip", { exact: true }).waitFor();
    assert.equal(await page.locator("#plan-empty").isVisible(), true);
    const first = await share(), firstArgs = first.request().postDataJSON();
    assert.equal(first.status(), 200);
    await page.locator("#created-link").waitFor({ state: "visible" });
    await closeShare();
    await action("archive");
    assert.ok((await state()).trip.archived_at);
    await archived();
    await comment("Comment while archived");
    await action("restore");
    assert.equal((await state()).trip.archived_at, null);
    assert.equal((await state()).trip.lifecycle_revision, 5);
    const beforeReplay = await mutationCount();
    await page.route("**/itinerary-api/create_itinerary_view_link", async (route) => {
      const cached = await route.fetch({ postData: JSON.stringify(firstArgs) });
      await route.fulfill({ response: cached });
    }, { times: 1 });
    assert.equal((await share()).status(), 200);
    await page.getByText(/The link cannot be recovered/).waitFor();
    await closeShare();
    assert.equal(await mutationCount(), beforeReplay);
    await action("archive");
    await archived();
    await action("restore");
    const held = deferred(), release = deferred();
    await page.route("**/itinerary-api/create_itinerary_view_link", async (route) => {
      const saved = await route.fetch();
      held.resolve();
      await release.promise;
      await route.fulfill({ response: saved });
    }, { times: 1 });
    const late = share();
    await held.promise;
    await closeShare();
    await comment("Newer than the held share");
    release.resolve();
    await late;
    await page.waitForFunction(() => !document.getElementById("create-invitation").disabled);
    await action("archive");
    await archived();
    await action("restore");
    await core.callFromWeb("add_itinerary_item", { tripId, expectedRevision: 1, ...key(), item: { type: "note", title: "Newly loaded fixture item", startDate: null, startTime: null, endDate: null, endTime: null, timeZone: null, endTimeZone: null, location: "", url: null, notes: "", openQuestion: "", status: "tentative", bookingNote: "" } }, owner);
    const readHeld = deferred(), readRelease = deferred();
    await page.route("**/itinerary-api/get_itinerary", async (route) => {
      const snapshot = await route.fetch();
      readHeld.resolve();
      await readRelease.promise;
      await route.fulfill({ response: snapshot });
    }, { times: 1 });
    await openDisclosure(page, "plan-more");
    await page.locator("#refresh").click();
    await readHeld.promise;
    await comment("Newer than the held read");
    readRelease.resolve();
    await page.waitForFunction(() => !document.getElementById("trip-filter").disabled);
    await page.getByText("Newly loaded fixture item", { exact: true }).first().waitFor();
    await action("archive");
    await archived();
    await action("restore");
    await core.callFromWeb("add_itinerary_comment", { tripId, body: "Another session changed this trip", ...key() }, owner);
    const beforeConflict = await mutationCount();
    await action("archive", 409);
    assert.equal((await state()).trip.archived_at, null);
    assert.equal(await mutationCount(), beforeConflict);
    await openDisclosure(page, "plan-more");
    await page.locator("#refresh").click();
    await page.waitForFunction(() => !document.getElementById("trip-filter").disabled);
    await openDisclosure(page, "plan-more");
    await openDisclosure(page, "trip-actions");
    await page.locator("#delete-trip").click();
    await page.locator("#lifecycle-name").fill("wrong");
    assert.equal(await page.locator("#lifecycle-confirm").isDisabled(), true);
    await page.locator("#lifecycle-name").fill("Fictional lifecycle trip");
    await page.waitForFunction(() => !document.getElementById("lifecycle-confirm").disabled);
    await core.callFromWeb("add_itinerary_comment", { tripId, body: "Change after destructive review", ...key() }, owner);
    const beforeDelete = await mutationCount(), deleteResponse = response("delete_trip");
    await page.locator("#lifecycle-confirm").click();
    assert.equal((await deleteResponse).status(), 409);
    await page.getByText(/Close this dialog and review again/).waitFor();
    assert.equal(await page.locator("#lifecycle-confirm").isDisabled(), true);
    assert.equal(await mutationCount(), beforeDelete);
    assert.equal((await state()).trip.id, tripId);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true, "desktop/mobile page has no horizontal overflow");
    assert.deepEqual(errors, []);
  });
}
